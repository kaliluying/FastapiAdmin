def build_analysis_prompt(
    *,
    evidence_type: str,
    content: str,
) -> str:
    """Build the full analysis prompt for a given evidence type and content."""
    type_instruction = TYPE_PROMPTS.get(evidence_type, TYPE_PROMPTS["其他材料"])
    # Truncate content to avoid token overflow
    truncated = content[:5000] if len(content) > 5000 else content
    if len(content) > 5000:
        truncated += "\n\n[提示：原始材料较长，以上仅展示前 5000 字符，请基于可获取内容分析，注明材料截断情况]"

    return (
        f"{BASE_SYSTEM}\n\n"
        f"{type_instruction}\n\n"
        f"=== 证据材料内容 ===\n"
        f"{truncated}\n"
    )
